const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('kick', {
  getState: () => ipcRenderer.invoke('state:get'),
  addChannel: (slug) => ipcRenderer.invoke('channels:add', slug),
  removeChannel: (slug) => ipcRenderer.invoke('channels:remove', slug),
  setFarming: (on) => ipcRenderer.invoke('farming:set', on),
  setMaxWatchers: (n) => ipcRenderer.invoke('maxWatchers:set', n),
  setRotation: (on) => ipcRenderer.invoke('rotation:set', on),
  setBonusTarget: (cost) => ipcRenderer.invoke('bonusTarget:set', cost),
  setAutostart: (on) => ipcRenderer.invoke('autostart:set', on),
  quit: () => ipcRenderer.invoke('app:quit'),
  setNotifyBonus: (on) => ipcRenderer.invoke('notifyBonus:set', on),
  startLimitTest: () => ipcRenderer.invoke('limitTest:start'),
  stopLimitTest: () => ipcRenderer.invoke('limitTest:stop'),
  setLowQuality: (on) => ipcRenderer.invoke('lowQuality:set', on),
  refresh: () => ipcRenderer.invoke('refresh'),
  openStore: (slug) => ipcRenderer.invoke('store:open', slug),
  showLogin: (platform) => ipcRenderer.invoke('login:show', platform),
  twitchSetApi: (cfg) => ipcRenderer.invoke('twitch:setApi', cfg),
  twitchConnectChat: () => ipcRenderer.invoke('twitch:connectChat'),
  twitchDisconnectChat: () => ipcRenderer.invoke('twitch:disconnectChat'),
  onToast: (cb) => ipcRenderer.on('toast', (_e, text) => cb(text)),
  onFocusToggle: (cb) => ipcRenderer.on('focus-toggle', () => cb()),
  logout: () => ipcRenderer.invoke('logout'),
  showChannel: (slug) => ipcRenderer.invoke('channel:show', slug),
  sendChat: (chatroomId, content) => ipcRenderer.invoke('chat:send', { chatroomId, content }),
  setNotifyChat: (on) => ipcRenderer.invoke('notifyChat:set', on),
  setSleepMode: (on) => ipcRenderer.invoke('sleepMode:set', on),
  toggleFavorite: (slug) => ipcRenderer.invoke('favorite:toggle', slug),
  addPurchase: (cost, platform) => ipcRenderer.invoke('purchase:add', cost, platform),
  setBonus: (platform, tipo, msLeft) => ipcRenderer.invoke('bonus:set', platform, tipo, msLeft),
  showPokeIdle: (id, bounds) => ipcRenderer.invoke('pokeidle:show', id, bounds),
  hidePokeIdle: () => ipcRenderer.invoke('pokeidle:hide'),
  startPokeRedeem: (tipo, platform) => ipcRenderer.invoke('redeem:start', tipo, platform),
  getPokeRedeem: (id) => ipcRenderer.invoke('redeem:get', id),
  cancelPokeRedeem: (id) => ipcRenderer.invoke('redeem:cancel', id),
  openAllPoke: (current, bounds) => ipcRenderer.invoke('pokeidle:openAll', current, bounds),
  pokeGrid: (on, current, bounds) => ipcRenderer.invoke('pokeidle:grid', on, current, bounds),
  closePokeIdle: (id) => ipcRenderer.invoke('pokeidle:close', id),
  addPokeAccount: (name, bounds) => ipcRenderer.invoke('pokeidle:add', name, bounds),
  removePokeAccount: (id) => ipcRenderer.invoke('pokeidle:remove', id),
  openCockpit: (id) => ipcRenderer.invoke('cockpit:open', id),
  switchAccount: (id) => ipcRenderer.invoke('tk:switch', id),
  addTkAccount: (name) => ipcRenderer.invoke('tk:add', name),
  removeTkAccount: (id) => ipcRenderer.invoke('tk:remove', id),
  listAccounts: () => ipcRenderer.invoke('accounts:list'),
  openAccount: (name) => ipcRenderer.invoke('accounts:open', name),
  createAccount: (opts) => ipcRenderer.invoke('accounts:create', opts),
  pokeIdleBounds: (bounds) => ipcRenderer.send('pokeidle:bounds', bounds),
  removePurchase: (t) => ipcRenderer.invoke('purchase:remove', t),
  openStoreSequence: (slugs) => ipcRenderer.invoke('stores:sequence', slugs),
  cancelStoreSequence: () => ipcRenderer.invoke('stores:cancel'),
  getReport: () => ipcRenderer.invoke('report:get'),
  saveReport: (rect) => ipcRenderer.invoke('report:save', rect),
  introDone: () => ipcRenderer.invoke('intro:done'),
  onSelect: (cb) => ipcRenderer.on('select', (_e, slug) => cb(slug)),
  onStatus: (cb) => ipcRenderer.on('status', (_e, s) => cb(s)),
  onChat: (cb) => ipcRenderer.on('chat', (_e, m) => cb(m)),
});
